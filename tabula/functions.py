"""Function symbol table: what Tabula simulates, and what Excel knows.

SUPPORTED   functions the evaluator implements (arity + which parameters
            accept ranges).  Single source of truth for the checker and the
            evaluator.
EXCEL_FUNCTIONS  names of real Excel functions.  A call to one of these that
            is not SUPPORTED is legal but unsimulated (its value is taken from
            Excel's cache and marked unverified); a call to anything else is an
            unknown function, the classic hallucination.
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class FunctionSpec:
    name: str
    min_args: int
    max_args: int | None          # None = variadic
    range_params: frozenset | str  # 'all' or a set of 0-based argument indexes

    def accepts_range(self, index: int) -> bool:
        return self.range_params == "all" or index in self.range_params


def _spec(name, lo, hi, ranges=frozenset()):
    return FunctionSpec(name, lo, hi, ranges if ranges == "all" else frozenset(ranges))


SUPPORTED: dict[str, FunctionSpec] = {s.name: s for s in [
    _spec("SUM", 1, None, "all"),
    _spec("AVERAGE", 1, None, "all"),
    _spec("MIN", 1, None, "all"),
    _spec("MAX", 1, None, "all"),
    _spec("COUNT", 1, None, "all"),
    _spec("COUNTA", 1, None, "all"),
    _spec("COUNTIF", 2, 2, {0}),
    _spec("SUMIF", 2, 3, {0, 2}),
    _spec("ROUND", 2, 2),
    _spec("ABS", 1, 1),
    _spec("SQRT", 1, 1),
    _spec("MOD", 2, 2),
    _spec("POWER", 2, 2),
    _spec("IF", 2, 3),
    _spec("IFERROR", 2, 2),
    _spec("AND", 1, None, "all"),
    _spec("OR", 1, None, "all"),
    _spec("NOT", 1, 1),
    _spec("LEN", 1, 1),
    _spec("CONCAT", 1, None, "all"),
    _spec("CONCATENATE", 1, None),
    _spec("UPPER", 1, 1),
    _spec("LOWER", 1, 1),
    _spec("TRIM", 1, 1),
    _spec("ISNUMBER", 1, 1),
    _spec("ISBLANK", 1, 1),
    _spec("ISERROR", 1, 1),
]}

