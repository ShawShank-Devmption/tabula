def classify(name: str) -> str:
    """'supported' | 'unsimulated' | 'unknown' for an upper-cased function name."""
    if name in SUPPORTED:
        return "supported"
    if name in EXCEL_FUNCTIONS:
        return "unsimulated"
    return "unknown"


def uses_only_supported(ast) -> bool:
    from .parser import Call, walk
    return all(n.fname in SUPPORTED for n in walk(ast) if isinstance(n, Call))
